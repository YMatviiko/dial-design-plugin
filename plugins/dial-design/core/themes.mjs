// Theme tokens the kit's CSS reads, with their fallback chains: var(--shadow-md-2, var(--shadow-md, #…)) is covered
// when any token in the chain is in the theme. Returns [{ token, chain }].
export function kitThemeTokens(kitCss) {
  const out = new Map();
  const re = /var\(--((?:bg|text|stroke|controls|shadow)-[\w-]+)\s*,?/g;
  let m;
  while ((m = re.exec(kitCss))) {
    const chain = [m[1]];
    let rest = kitCss.slice(re.lastIndex, re.lastIndex + 300), n;
    while ((n = rest.match(/^\s*var\(--([\w-]+)\s*,?/))) { chain.push(n[1]); rest = rest.slice(n[0].length); }
    if (!out.has(m[1]) || out.get(m[1]).length < chain.length) out.set(m[1], chain);
  }
  return [...out].map(([token, chain]) => ({ token, chain }));
}
// Kit tokens a theme doesn't cover (no token of the chain defined): they keep the kit's light fallback in that theme.
export const uncovered = (tokens, t) => tokens.filter(({ chain }) => !chain.some((c) => c in t.colors)).map((x) => x.token);

