// DIAL themes: the saved copy of epam/ai-dial-chat-themes static/config.json (core/themes/config.json) and the
// CSS / HTML generated from it. Shared by kit-lookup.mjs (theme commands, prototype theme block), the HTML
// validator (checks the block is unedited) and check-release.mjs. Dependency-free.
//
// How DIAL applies a theme (ai-dial-chat ThemeContext + public/theme-init.js): every key of theme.colors is
// written to <html> as a custom property (--bg-layer-base: #10151E). The kit's CSS reads each colour as
// var(--token, <light fallback>), so swapping the properties switches the whole UI. Modes: light, dark, system.
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const THEMES_DIR = join(here, 'themes');
export const THEMES_FILE = join(THEMES_DIR, 'config.json');
export const SOURCE_FILE = join(THEMES_DIR, 'SOURCE.json');
export const THEMES_URL = 'https://raw.githubusercontent.com/epam/ai-dial-chat-themes/main/static/config.json';

export const loadThemes = () => JSON.parse(readFileSync(THEMES_FILE, 'utf8'));
export const loadSource = () => JSON.parse(readFileSync(SOURCE_FILE, 'utf8'));
export const theme = (cfg, id) => cfg.themes.find((t) => t.id === id) ?? null;

const decls = (colors, indent) => Object.entries(colors).filter(([, v]) => typeof v === 'string').map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');

// The theme as CSS: light on :root, dark on :root[data-theme="dark"]. `color-scheme` makes native scrollbars and
// form controls follow the theme too.
export function themeCss(cfg = loadThemes()) {
  const light = theme(cfg, 'light'), dark = theme(cfg, 'dark');
  if (!light || !dark) throw new Error('themes config needs a "light" and a "dark" theme');
  return `:root {\n  color-scheme: light;\n${decls(light.colors, '  ')}\n}\n:root[data-theme="dark"] {\n  color-scheme: dark;\n${decls(dark.colors, '  ')}\n}`;
}

// Extra rules the prototype theme block needs: show an asset's light or dark version, and place the toggle.
export const THEME_BLOCK_RULES = `:root[data-theme="dark"] [data-theme-only="light"],
:root:not([data-theme="dark"]) [data-theme-only="dark"] { display: none !important; }
[data-kit-theme-toggle] { position: fixed; right: 16px; bottom: 16px; z-index: 2147483000; }`;

// The <style> text of the prototype theme block (the validator compares a page's block with this, so it can't drift).
export const themeBlockCss = (cfg = loadThemes()) => {
  const src = loadSource();
  return `/* kit-theme: generated by kit-lookup.mjs from ${src.repo} @ ${src.commit} — don't edit, regenerate */\n${themeCss(cfg)}\n${THEME_BLOCK_RULES}`;
};

// Runs in <head> before first paint: ?theme=light|dark|system, else the stored choice, else light. ?toggle=off hides
// the toggle button (for screenshots).
export const THEME_BLOCK_SCRIPT = `(function () {
  var KEY = 'dial-prototype-theme', root = document.documentElement;
  var stored = null;
  try { stored = localStorage.getItem(KEY); } catch (e) {}
  var asked = new URLSearchParams(location.search).get('theme') || stored || 'light';
  var media = window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : null;
  var mode = asked;
  function paint() { root.setAttribute('data-theme', mode === 'system' ? (media && media.matches ? 'dark' : 'light') : mode); }
  paint();
  if (media && media.addEventListener) media.addEventListener('change', function () { if (mode === 'system') paint(); });
  window.dialTheme = {
    get: function () { return root.getAttribute('data-theme'); },
    set: function (next) { mode = next; paint(); try { localStorage.setItem(KEY, next); } catch (e) {} }
  };
  document.addEventListener('click', function (e) {
    var b = e.target.closest && e.target.closest('[data-theme-set]');
    if (b) window.dialTheme.set(b.getAttribute('data-theme-set'));
  });
  document.addEventListener('DOMContentLoaded', function () {
    var tpl = document.getElementById('kit-theme-toggle');
    if (new URLSearchParams(location.search).get('toggle') === 'off') return;
    if (tpl && !document.querySelector('[data-kit-theme-toggle]')) document.body.appendChild(tpl.content.cloneNode(true));
  });
})();`;

// WCAG contrast ratio of two #RRGGBB[AA] colours (alpha composited over `under`, default white).
export function contrast(fg, bg, under = '#FFFFFF') {
  const rgb = (h) => { const x = h.replace('#', ''); const n = x.length <= 4 ? x.split('').map((c) => c + c).join('') : x; return [0, 2, 4, 6].map((i) => (i < n.length ? parseInt(n.slice(i, i + 2), 16) : 255)); };
  const over = (top, base) => { const a = top[3] / 255; return top.slice(0, 3).map((c, i) => c * a + base[i] * (1 - a)); };
  const lum = (c) => { const [r, g, b] = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
  const base = over(rgb(bg), rgb(under).slice(0, 3));
  const top = over(rgb(fg), base);
  const [l1, l2] = [lum(top), lum(base)].sort((a, b) => b - a);
  return (l1 + 0.05) / (l2 + 0.05);
}

